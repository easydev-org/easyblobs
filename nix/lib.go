// Package nix implements the Nix binary cache protocol (nix-serve face) with
// pull-through: nix-cache-info, per-store-path narinfo metadata, and NAR
// archives are fetched from the configured upstream (cache.nixos.org),
// cached in the CAS, and served byte-for-byte so NAR signature/ digest
// verification by the nix client stays intact.
//
// Wire format:
//
//	/nix-cache-info                        ("StoreDir: /nix/store\nWantMassQuery: 1\nPriority: 40\n")
//	/<hash>.narinfo                        (text metadata: URL, NarHash, NarSize, Sig, ...)
//	/nar/<hash>.nar[.xz|zst]               (the archive itself)
//
// Repository layout served here: everything under /artifacts/nix/ maps 1:1 onto
// the upstream cache root (the binary cache is one global namespace).
package nix

import (
	"net/http"
	"strings"

	"github.com/easydev-org/easyblobs/core"
)

type State struct {
	Registry *easyblobkit.Registry
	Auth     easyblobkit.Auth
	// Hosted serves /artifacts/nix/_hosted/<repo>/... (self-published cache).
	//
	// A binary cache is NOT read-only. `nix copy --to <url>` is the protocol's
	// own upload command and it PUTs the same two shapes a GET reads:
	//   PUT /<hash>.narinfo
	//   PUT /nar/<hash>.nar
	// nix-serve, Cachix and Attic all implement that. This adapter used to
	// answer 405 to every non-GET, which is a property of THIS implementation,
	// not of the protocol - the same confusion as reading Kind: Mirror as
	// "cannot be written to".
	Hosted *easyblobkit.HostedHandler
}

func NewHandler(reg *easyblobkit.Registry, cfg map[string]any) (http.Handler, error) {
	s := &State{Registry: reg}
	if a, ok := cfg["auth"].(easyblobkit.Auth); ok {
		s.Auth = a
	}
	s.Hosted = &easyblobkit.HostedHandler{
		Format: "nix",
		Store:  easyblobkit.HostedStore{Registry: reg},
		Auth:   s.Auth,
		// No Generator: a binary cache has no index to synthesise. narinfo is
		// the index, and it is uploaded file by file.
	}
	return s, nil
}

func init() { easyblobkit.Register("nix", NewHandler) }

// ServeHTTP maps /artifacts/nix/<path> onto the upstream cache root.
func (s *State) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	// A self-published cache is addressed under the reserved "_hosted/<repo>/"
	// segment. Those paths are NOT proxied: a hosted cache is authoritative for
	// what it holds, and falling through to cache.nixos.org would serve
	// upstream bytes for a path the operator published themselves.
	if repo, sub, hosted := easyblobkit.HostedRequest(r, "/artifacts/nix"); hosted {
		s.serveHosted(w, r, repo, sub)
		return
	}

	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		w.WriteHeader(http.StatusMethodNotAllowed)
		return
	}
	path := strings.TrimPrefix(r.URL.Path, "/artifacts/nix/")
	path = strings.TrimPrefix(path, "nix/")
	path = strings.Trim(path, "/")
	if path == "" || path == "nix-cache-info" {
		easyblobkit.OctetResponse(w, r, []byte(defaultNixCacheInfo))
		return
	}
	if !isCachePath(path) {
		easyblobkit.Error(w, http.StatusNotFound, "not found")
		return
	}

	// Cache-first with shared freshness (single global repo "cache").
	ct := mediaTypeOf(path)
	res := s.Registry.FetchCachedPath(r.Context(), "nix", "cache", path, "/"+path, "",
		easyblobkit.PathCachePolicy{MediaType: ct, BlobName: path})
	if !res.OK {
		easyblobkit.WriteCacheResultError(w, res)
		return
	}
	if easyblobkit.ServeCachedBlob(w, r, s.Registry.Blobs, r.Context(), res.Artifact, ct, path) {
		return
	}
	easyblobkit.Error(w, http.StatusBadGateway, "cache error")
}

// serveHosted routes an upload/download/delete on a self-published cache.
func (s *State) serveHosted(w http.ResponseWriter, r *http.Request, repo, rest string) {
	rest = strings.Trim(rest, "/")
	// The same path shapes the read side accepts, so a client cannot publish a
	// key that a nix client would then refuse to read.
	if rest != "nix-cache-info" && !isCachePath(rest) {
		easyblobkit.Error(w, http.StatusNotFound, "not a cache path")
		return
	}
	switch r.Method {
	case http.MethodGet, http.MethodHead:
		if rest == "nix-cache-info" {
			// The cache identity is a property of the mount, not a stored file.
			easyblobkit.OctetResponse(w, r, []byte(defaultNixCacheInfo))
			return
		}
		s.Hosted.Get(w, r, repo, rest)
	case http.MethodPut, http.MethodPost:
		if rest == "nix-cache-info" {
			// Writing it would let one upload redefine the mount's StoreDir.
			easyblobkit.Error(w, http.StatusMethodNotAllowed,
				"nix-cache-info is generated by the mount, not uploaded")
			return
		}
		s.Hosted.Put(w, r, repo, rest)
	case http.MethodDelete:
		s.Hosted.Delete(w, r, repo, rest)
	default:
		w.WriteHeader(http.StatusMethodNotAllowed)
	}
}

// defaultNixCacheInfo is served at the cache root (mirrors cache.nixos.org).
const defaultNixCacheInfo = "StoreDir: /nix/store\nWantMassQuery: 1\nPriority: 40\n"

// isCachePath allows only the three real cache path shapes (defense against
// using the adapter as a generic open proxy): nix-cache-info, <32 hex>
// [optional suffix].narinfo, and nar/<hex>.nar[.ext].
func isCachePath(path string) bool {
	switch {
	case path == "nix-cache-info":
		return true
	case strings.HasSuffix(path, ".narinfo"):
		h := strings.TrimSuffix(path, ".narinfo")
		return isHex32(h)
	case strings.HasPrefix(path, "nar/"):
		base := strings.TrimPrefix(path, "nar/")
		dot := strings.IndexByte(base, '.')
		if dot < 0 {
			return false
		}
		return isHex32(base[:dot]) && strings.HasPrefix(base[dot:], ".nar")
	}
	return false
}

// isHex32 validates a Nix store-path hash (32 chars of the nix base32
// alphabet: digits + lowercase letters, minus e/o/u).
func isHex32(s string) bool {
	if len(s) != 32 {
		return false
	}
	for _, c := range s {
		ok := ('0' <= c && c <= '9') || ('a' <= c && c <= 'z')
		if !ok {
			return false
		}
	}
	return true
}

func mediaTypeOf(path string) string {
	switch {
	case path == "nix-cache-info":
		return "text/plain"
	case strings.HasSuffix(path, ".narinfo"):
		return "text/x-nix-narinfo"
	case strings.HasSuffix(path, ".xz"):
		return "application/x-xz"
	case strings.HasSuffix(path, ".zst"):
		return "application/zstd"
	default:
		return "application/octet-stream"
	}
}
